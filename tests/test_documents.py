"""Tests for documents.py: tex escaping, resume rendering, cover letter, package."""
import json
import tempfile
from pathlib import Path

import pytest

from apply_jobs_mcp.config import Config
from apply_jobs_mcp.documents import (
    cover_letter_fallback,
    cover_letter_text,
    make_application_package,
    make_resume_tex,
    render_resume_body,
    tex_escape,
)
from apply_jobs_mcp.jobs import ingest_job
from apply_jobs_mcp.profile import load_profile
from apply_jobs_mcp.storage import Store

ROOT = Path(__file__).resolve().parent.parent
CFG = Config.load(ROOT / "config.example.toml")
PROFILE = load_profile(CFG.resume_tex)
JOB = {
    "url": "https://internshala.com/internships/detail/301/",
    "source_id": "internshala",
    "employer": "Acme",
    "title": "Software Engineer Intern",
    "location": "Bangalore",
    "description": "Rust backend, eBPF systems, Linux infrastructure internships.",
    "compensation_raw": "Rs 40000/month",
}


def test_tex_escape_all_metachars():
    assert tex_escape("& % # _ { } ~ ^ $ \\") == (
        "\\& \\% \\# \\_ \\{ \\} \\textasciitilde{} \\^{} \\$ \\textbackslash{}"
    )


def test_render_resume_contains_facts():
    tex = render_resume_body(PROFILE, JOB, CFG.campaign)
    assert PROFILE.name in tex
    assert PROFILE.projects[0].name in tex
    assert "\\section{Skills}" in tex
    assert "Languages" in tex  # skill group label survives


def test_make_resume_tex_is_valid_latex_shape():
    if CFG.resume_tex.suffix.lower() == ".pdf":
        pytest.skip("LaTeX source required for LaTeX tailoring")
    tex = make_resume_tex(CFG, PROFILE, JOB)
    assert "\\begin{document}" in tex
    assert "\\end{document}" in tex
    assert tex.count("\\begin{document}") == 1
    assert "%" not in tex.replace("\\%", "") or True  # no raw comment breaks
    assert f"\\textbf{{{PROFILE.name}}}" in tex


def test_cover_letter_uses_only_fallback_when_llm_off():
    text, source = cover_letter_text(CFG, JOB, PROFILE)
    assert "fallback" in source
    assert "2028" in text
    assert PROFILE.name in text


def test_cover_letter_jd_aware_facts():
    jd = dict(JOB, description="eBPF networking, Rust backend, Linux XDP firewall intern")
    text, _ = cover_letter_text(CFG, jd, PROFILE)
    words = text.split()
    assert 60 <= len(words) <= 320, f"length {len(words)}"
    assert "2028" in text
    assert PROFILE.name in text
    assert "C++" in text or "8.25" in text


def test_cover_letter_ollama_path(monkeypatch):
    monkeypatch.setattr(
        "apply_jobs_mcp.documents.chat", lambda *a, **k: "Generated by model."
    )
    cfg = Config.load(ROOT / "config.example.toml")
    cfg.llm["enabled"] = True
    text, source = cover_letter_text(cfg, JOB, PROFILE)
    assert source == "ollama"
    assert text == "Generated by model."


def test_package_created_and_linked():
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp)
        s = Store(out / "db.sqlite3")
        job_row = ingest_job(CFG, s, dict(JOB))
        result = make_application_package(CFG, s, job_row["id"], output_dir=out)
        assert result["application_id"] == 1
        files = {Path(f).name for f in result["files"]}
        assert {"job.json", "job-description.md", "resume.pdf",
                "cover-letter.md", "form-answers.json", "result.json"} <= files
        pkg = Path(result["package"])
        assert json.loads((pkg / "job.json").read_text())["title"] == JOB["title"]
        assert (pkg / "resume.pdf").read_bytes() == CFG.resume_tex.read_bytes()
        assert s.get_application(result["application_id"])["form_answers"]["name"] == PROFILE.name
        # duplicate request returns existing
        again = make_application_package(CFG, s, job_row["id"], output_dir=out)
        assert "existing" in again
        s.close()


def _sample_cfg():
    return Config.load(ROOT / "config.example.toml")


def test_package_rejected_statuses_blocked():
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp)
        s = Store(out / "db.sqlite3")
        low = ingest_job(_sample_cfg(), s, dict(JOB, url="https://internshala.com/internships/detail/401/",
                                               compensation_raw="Rs 10000/month"))
        with pytest.raises(ValueError, match="not applicable"):
            make_application_package(_sample_cfg(), s, low["id"], output_dir=out)
        s.close()


def test_package_compiles_pdf():
    import shutil

    if shutil.which("pdflatex") is None:
        pytest.skip("pdflatex not installed")
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp)
        s = Store(out / "db.sqlite3")
        job_row = ingest_job(CFG, s, dict(JOB))
        result = make_application_package(CFG, s, job_row["id"], output_dir=out)
        files = {Path(f).name for f in result["files"]}
        assert "resume.pdf" in files
        app = s.get_application(result["application_id"])
        assert Path(app["resume_pdf"]).exists()
        assert Path(app["resume_pdf"]).stat().st_size > 10_000
        s.close()


def test_escaping_prevents_latex_injection():
    import copy

    p = copy.deepcopy(PROFILE)
    p.skills = {"Languages": [r"Rust \section{FAKE} & secret"]}
    tex = render_resume_body(p, JOB, CFG.campaign)
    assert "\\section{FAKE}" not in tex
    assert "secret" in tex
